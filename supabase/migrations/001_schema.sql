-- เครื่องพิมพ์แยกตามครัว
-- ครัวที่ตั้ง print_mode = 'station' จะมีอุปกรณ์ประจำครัว (เปิดหน้า "จอครัว")
-- ต่อเครื่องพิมพ์ของครัวนั้น หลังคิดเงินระบบสร้าง "ใบงาน" ในคิว แล้วเครื่องประจำครัว
-- ดึงไปพิมพ์เอง (แจ้งเตือนแบบ realtime + ตรวจซ้ำทุกช่วงเวลา กันพลาด)
-- ครัว print_mode = 'cashier' พิมพ์ที่เครื่องคิดเงินเหมือนเดิม
-- =====================================================================

-- ต้องรันส่วนนี้หลังสร้างฟังก์ชันด้านบน (ฟังก์ชัน plpgsql อ้างถึงตอนเรียกใช้จริงเท่านั้น)
ALTER TABLE kitchens ADD COLUMN IF NOT EXISTS print_mode TEXT NOT NULL DEFAULT 'cashier';
DO $$ BEGIN
  ALTER TABLE kitchens ADD CONSTRAINT kitchens_print_mode_check CHECK (print_mode IN ('cashier', 'station'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
ALTER TABLE kitchens ADD COLUMN IF NOT EXISTS station_seen_at TIMESTAMPTZ;  -- เครื่องประจำครัวออนไลน์ล่าสุด

CREATE TABLE IF NOT EXISTS kitchen_tickets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  kitchen_id BIGINT REFERENCES kitchens(id) ON DELETE SET NULL,
  kitchen_name TEXT NOT NULL,
  kind TEXT NOT NULL DEFAULT 'order' CHECK (kind IN ('order', 'void')),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'printed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  printed_at TIMESTAMPTZ,
  printed_by TEXT
);
CREATE INDEX IF NOT EXISTS idx_kitchen_tickets_queue ON kitchen_tickets(kitchen_id, status);
CREATE INDEX IF NOT EXISTS idx_kitchen_tickets_order ON kitchen_tickets(order_id);
