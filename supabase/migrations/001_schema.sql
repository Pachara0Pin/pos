-- ---------- ตารางหลัก ----------
CREATE TABLE IF NOT EXISTS kitchens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS menu_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'ทั่วไป',
  price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
  available SMALLINT NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL
);
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS kitchen_id BIGINT REFERENCES kitchens(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS payment_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('promptpay','image')),
  promptpay_id TEXT,
  account_name TEXT,
  image_data TEXT,
  active SMALLINT NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no TEXT NOT NULL UNIQUE,
  order_type TEXT NOT NULL CHECK (order_type IN ('dine_in','takeaway')),
  table_no TEXT,
  subtotal NUMERIC(12,2) NOT NULL,
  discount NUMERIC(12,2) NOT NULL DEFAULT 0,
  total NUMERIC(12,2) NOT NULL,
  payment_method TEXT NOT NULL CHECK (payment_method IN ('cash','qr')),
  payment_account_name TEXT,
  cash_received NUMERIC(12,2),
  change_amount NUMERIC(12,2),
  status TEXT NOT NULL DEFAULT 'paid' CHECK (status IN ('paid','void')),
  staff_id BIGINT,
  staff_name TEXT,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_orders_created ON orders(created_at);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS request_id TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS idx_orders_request_id ON orders(request_id);
-- พนักงานที่ขาย (บัญชี Supabase Auth); staff_id เดิมเก็บไว้เป็นประวัติของบิลเก่า
ALTER TABLE orders ADD COLUMN IF NOT EXISTS staff_uid UUID;
ALTER TABLE orders DROP CONSTRAINT IF EXISTS orders_staff_id_fkey;

CREATE TABLE IF NOT EXISTS order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  menu_item_id BIGINT,
  name TEXT NOT NULL,
  price NUMERIC(12,2) NOT NULL,
  qty INTEGER NOT NULL CHECK (qty > 0),
  note TEXT,
  line_total NUMERIC(12,2) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_order_items_order ON order_items(order_id);
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS kitchen_id BIGINT;
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS kitchen_name TEXT;

-- ---------- ผู้ใช้: ผูกกับ Supabase Auth ----------
-- ล็อกอินด้วยชื่อผู้ใช้ → อีเมลภายใน <username>@pos.local (ไม่มีการส่งอีเมลจริง)
CREATE TABLE IF NOT EXISTS profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  username TEXT NOT NULL UNIQUE CHECK (username ~ '^[a-z0-9_.-]{3,30}$'),
  display_name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin','staff')),
  created_at TEXT NOT NULL
);

-- ---------- ฟังก์ชันช่วย ----------
CREATE OR REPLACE FUNCTION public.bkk_now() RETURNS TEXT
LANGUAGE sql STABLE AS $$ SELECT to_char(now() AT TIME ZONE 'Asia/Bangkok', 'YYYY-MM-DD HH24:MI:SS') $$;

-- สิทธิ์ของผู้ใช้ที่ล็อกอินอยู่ (null = ไม่มีสิทธิ์/ไม่ได้ล็อกอิน)
CREATE OR REPLACE FUNCTION public.app_role() RETURNS TEXT
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT role FROM profiles WHERE id = auth.uid()
$$;

-- บิลพร้อมรายการ เป็น JSON (รูปแบบเดียวกับที่หน้าเว็บใช้)
CREATE OR REPLACE FUNCTION public.order_json(p_id BIGINT) RETURNS JSONB
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT to_jsonb(o) || jsonb_build_object('items', COALESCE(
    (SELECT jsonb_agg(to_jsonb(i) ORDER BY i.id) FROM order_items i WHERE i.order_id = o.id), '[]'::jsonb))
  FROM orders o WHERE o.id = p_id
$$;

