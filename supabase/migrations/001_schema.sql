-- ---------- คิดเงิน ----------
-- p: { items:[{menu_item_id, qty, note}], order_type, table_no, discount,
--      payment_method, cash_received, payment_account_id, request_id }
-- ส่งซ้ำด้วย request_id เดิม (เน็ตหลุดแล้วลองใหม่) จะได้บิลเดิม ไม่เกิดบิลซ้ำ
CREATE OR REPLACE FUNCTION public.checkout(p JSONB) RETURNS JSONB
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_role TEXT := app_role();
  v_staff TEXT;
  v_req TEXT := NULLIF(p->>'request_id', '');
  v_type TEXT := p->>'order_type';
  v_method TEXT := p->>'payment_method';
  v_items JSONB := p->'items';
  v_sub NUMERIC := 0;
  v_disc NUMERIC;
  v_total NUMERIC;
  v_cash NUMERIC;
  v_change NUMERIC;
  v_acc TEXT;
  v_now TEXT := bkk_now();
  v_count INT;
  v_id BIGINT;
  v_existing BIGINT;
  it JSONB;
  m RECORD;
  v_qty INT;
BEGIN
  IF v_role IS NULL THEN RAISE EXCEPTION 'กรุณาเข้าสู่ระบบ' USING ERRCODE = '42501'; END IF;
  IF v_req IS NOT NULL AND v_req !~ '^[A-Za-z0-9-]{8,64}$' THEN v_req := NULL; END IF;

  -- ล็อกการออกเลขบิล กันหลายเครื่องกดพร้อมกันแล้วได้เลขซ้ำ
  PERFORM pg_advisory_xact_lock(7001);
  IF v_req IS NOT NULL THEN
    SELECT id INTO v_existing FROM orders WHERE request_id = v_req;
    IF v_existing IS NOT NULL THEN RETURN order_json(v_existing); END IF;
  END IF;

  IF jsonb_typeof(v_items) <> 'array' OR jsonb_array_length(v_items) = 0 THEN RAISE EXCEPTION 'ยังไม่มีรายการอาหาร'; END IF;
  IF jsonb_array_length(v_items) > 200 THEN RAISE EXCEPTION 'รายการมากเกินไป'; END IF;
  IF v_type NOT IN ('dine_in', 'takeaway') OR v_type IS NULL THEN RAISE EXCEPTION 'กรุณาเลือกทานที่ร้านหรือกลับบ้าน'; END IF;

  -- ราคาจากฐานข้อมูลเสมอ (ไม่เชื่อราคาที่หน้าเว็บส่งมา)
  FOR it IN SELECT * FROM jsonb_array_elements(v_items) LOOP
    SELECT * INTO m FROM menu_items WHERE id = (it->>'menu_item_id')::BIGINT;
    IF NOT FOUND OR m.available <> 1 THEN RAISE EXCEPTION 'มีรายการที่ไม่พร้อมขาย กรุณาตรวจสอบ'; END IF;
    v_qty := floor((it->>'qty')::NUMERIC);
    IF v_qty IS NULL OR v_qty < 1 OR v_qty > 999 THEN RAISE EXCEPTION 'จำนวนไม่ถูกต้อง'; END IF;
    v_sub := v_sub + round(m.price * v_qty, 2);
  END LOOP;

  v_disc := LEAST(GREATEST(COALESCE(NULLIF(p->>'discount', '')::NUMERIC, 0), 0), v_sub);
  v_disc := round(v_disc, 2);
  v_total := v_sub - v_disc;

  IF v_method = 'cash' THEN
    v_cash := round(COALESCE(NULLIF(p->>'cash_received', '')::NUMERIC, 0), 2);
    IF v_cash < v_total THEN RAISE EXCEPTION 'รับเงินไม่พอ'; END IF;
    v_change := v_cash - v_total;
  ELSIF v_method = 'qr' THEN
    SELECT name INTO v_acc FROM payment_accounts WHERE id = NULLIF(p->>'payment_account_id', '')::BIGINT;
    IF v_acc IS NULL THEN RAISE EXCEPTION 'กรุณาเลือกบัญชีรับเงิน'; END IF;
  ELSE
    RAISE EXCEPTION 'กรุณาเลือกวิธีชำระเงิน';
  END IF;

  SELECT display_name INTO v_staff FROM profiles WHERE id = auth.uid();
  SELECT count(*) INTO v_count FROM orders WHERE substr(created_at, 1, 10) = substr(v_now, 1, 10);

  INSERT INTO orders (order_no, order_type, table_no, subtotal, discount, total, payment_method,
    payment_account_name, cash_received, change_amount, staff_uid, staff_name, created_at, request_id)
  VALUES (replace(substr(v_now, 1, 10), '-', '') || '-' || lpad((v_count + 1)::TEXT, 4, '0'),
    v_type, CASE WHEN v_type = 'dine_in' THEN left(NULLIF(p->>'table_no', ''), 20) END,
    v_sub, v_disc, v_total, v_method, v_acc, v_cash, v_change, auth.uid(), v_staff, v_now, v_req)
  RETURNING id INTO v_id;

  INSERT INTO order_items (order_id, menu_item_id, name, price, qty, note, line_total, kitchen_id, kitchen_name)
  SELECT v_id, mi.id, mi.name, mi.price, x.qty, left(COALESCE(x.note, ''), 200), round(mi.price * x.qty, 2), mi.kitchen_id, k.name
  FROM jsonb_array_elements(v_items) WITH ORDINALITY AS e(j, n)
  CROSS JOIN LATERAL (SELECT (e.j->>'menu_item_id')::BIGINT AS mid, floor((e.j->>'qty')::NUMERIC)::INT AS qty, e.j->>'note' AS note) x
  JOIN menu_items mi ON mi.id = x.mid
  LEFT JOIN kitchens k ON k.id = mi.kitchen_id
  ORDER BY e.n;

  PERFORM queue_kitchen_tickets(v_id, 'order');
  RETURN order_json(v_id);
END $$;

-- ---------- ยกเลิกบิล (admin) ----------
CREATE OR REPLACE FUNCTION public.void_order(p_id BIGINT) RETURNS JSONB
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF app_role() IS DISTINCT FROM 'admin' THEN RAISE EXCEPTION 'เฉพาะผู้ดูแลระบบ' USING ERRCODE = '42501'; END IF;
  IF NOT EXISTS (SELECT 1 FROM orders WHERE id = p_id) THEN RAISE EXCEPTION 'ไม่พบบิล'; END IF;
  UPDATE orders SET status = 'void' WHERE id = p_id AND status = 'paid';
  -- เพิ่งยกเลิก (ไม่ใช่ยกเลิกซ้ำ) → ส่งใบยกเลิกไปเครื่องพิมพ์ของครัวที่เกี่ยวข้อง
  IF FOUND THEN PERFORM queue_kitchen_tickets(p_id, 'void'); END IF;
  RETURN order_json(p_id);
END $$;

