--   * พนักงาน (staff) อ่านได้ แต่เขียนได้เฉพาะผ่านฟังก์ชัน checkout
--   * ผู้ดูแล (admin) แก้เมนู/ครัว/บัญชี QR ได้ ยกเลิกบิลและดูรายงานได้
--   * ยอดเงินและเลขบิลคำนวณในฐานข้อมูลเสมอ (แก้จากหน้าเว็บไม่ได้)
