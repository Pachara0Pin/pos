-- แจ้งเตือน realtime เมื่อมีใบงานใหม่ (Supabase Realtime; RLS ยังมีผล)
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime')
     AND NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND tablename = 'kitchen_tickets') THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.kitchen_tickets;
  END IF;
END $$;

-- สร้างใบงานของบิล สำหรับครัวที่ใช้เครื่องพิมพ์ประจำครัว (เรียกจาก checkout / void_order)
CREATE OR REPLACE FUNCTION public.queue_kitchen_tickets(p_order_id BIGINT, p_kind TEXT) RETURNS VOID
LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  INSERT INTO kitchen_tickets (order_id, kitchen_id, kitchen_name, kind)
  SELECT DISTINCT p_order_id, k.id, k.name, p_kind
  FROM order_items i JOIN kitchens k ON k.id = i.kitchen_id
  WHERE i.order_id = p_order_id AND k.print_mode = 'station'
$$;

-- เครื่องประจำครัว: แจ้งว่าออนไลน์ แล้ว "รับ" ใบงานที่รอพิมพ์ทั้งหมดของครัว
-- รับแล้วสถานะเป็น printed ทันที (FOR UPDATE SKIP LOCKED: ถ้ามี 2 เครื่องในครัวเดียว ใบงานไม่พิมพ์ซ้ำ)
-- p_order_id: ใช้ตอนเครื่องคิดเงินพิมพ์แทน (เครื่องครัวออฟไลน์) เฉพาะบิลนั้น
CREATE OR REPLACE FUNCTION public.claim_kitchen_tickets(p_kitchen_id BIGINT, p_order_id BIGINT DEFAULT NULL) RETURNS JSONB
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_name TEXT;
  r JSONB;
BEGIN
  IF app_role() IS NULL THEN RAISE EXCEPTION 'กรุณาเข้าสู่ระบบ' USING ERRCODE = '42501'; END IF;
  SELECT display_name INTO v_name FROM profiles WHERE id = auth.uid();
  IF p_order_id IS NULL THEN
    UPDATE kitchens SET station_seen_at = now() WHERE id = p_kitchen_id;
  END IF;

  WITH picked AS (
    SELECT id FROM kitchen_tickets
    WHERE kitchen_id = p_kitchen_id AND status = 'pending' AND (p_order_id IS NULL OR order_id = p_order_id)
    ORDER BY id FOR UPDATE SKIP LOCKED
  ), claimed AS (
    UPDATE kitchen_tickets t SET status = 'printed', printed_at = now(), printed_by = v_name
    FROM picked WHERE t.id = picked.id
    RETURNING t.*
  )
  SELECT COALESCE(jsonb_agg(to_jsonb(c) || jsonb_build_object('order', order_json(c.order_id)) ORDER BY c.id), '[]') INTO r
  FROM claimed c;
  RETURN r;
END $$;

REVOKE ALL ON FUNCTION public.queue_kitchen_tickets(BIGINT, TEXT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.claim_kitchen_tickets(BIGINT, BIGINT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_kitchen_tickets(BIGINT, BIGINT) TO authenticated;

-- ---------- รายงาน (admin) ----------
-- p_prefix: 'YYYY-MM-DD' (รายวัน) หรือ 'YYYY-MM' (รายเดือน)
CREATE OR REPLACE FUNCTION public.sales_summary(p_prefix TEXT) RETURNS JSONB
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  n INT := length(p_prefix);
  r JSONB;
BEGIN
  IF app_role() IS DISTINCT FROM 'admin' THEN RAISE EXCEPTION 'เฉพาะผู้ดูแลระบบ' USING ERRCODE = '42501'; END IF;
  IF p_prefix !~ '^\d{4}-\d{2}(-\d{2})?$' THEN RAISE EXCEPTION 'รูปแบบวันที่ไม่ถูกต้อง'; END IF;

  WITH paid AS (SELECT * FROM orders WHERE status = 'paid' AND substr(created_at, 1, n) = p_prefix)
  SELECT jsonb_build_object(
    'orders', (SELECT count(*) FROM paid),
    'sales', (SELECT COALESCE(sum(total), 0) FROM paid),
    'discount', (SELECT COALESCE(sum(discount), 0) FROM paid),
    'voided', (SELECT count(*) FROM orders WHERE status = 'void' AND substr(created_at, 1, n) = p_prefix),
    'byPayment', COALESCE((SELECT jsonb_agg(x) FROM (SELECT payment_method AS key, count(*) AS orders, sum(total) AS sales FROM paid GROUP BY 1) x), '[]'),
    'byType', COALESCE((SELECT jsonb_agg(x) FROM (SELECT order_type AS key, count(*) AS orders, sum(total) AS sales FROM paid GROUP BY 1) x), '[]'),
    'byAccount', COALESCE((SELECT jsonb_agg(x) FROM (SELECT payment_account_name AS key, count(*) AS orders, sum(total) AS sales FROM paid WHERE payment_method = 'qr' GROUP BY 1) x), '[]'),
    'topItems', COALESCE((SELECT jsonb_agg(x) FROM (
        SELECT i.name, sum(i.qty) AS qty, sum(i.line_total) AS sales FROM order_items i JOIN paid o ON o.id = i.order_id
        GROUP BY i.name ORDER BY 2 DESC, 3 DESC LIMIT 15) x), '[]'),
    'hourly', COALESCE((SELECT jsonb_agg(x ORDER BY x.hour) FROM (
        SELECT substr(created_at, 12, 2)::INT AS hour, count(*) AS orders, sum(total) AS sales FROM paid GROUP BY 1) x), '[]'),
    'daily', COALESCE((SELECT jsonb_agg(x ORDER BY x.date) FROM (
        SELECT substr(created_at, 1, 10) AS date, count(*) AS orders, sum(total) AS sales,
          sum(CASE WHEN payment_method = 'cash' THEN total ELSE 0 END) AS cash,
          sum(CASE WHEN payment_method = 'qr' THEN total ELSE 0 END) AS qr
        FROM paid GROUP BY 1) x), '[]')
  ) INTO r;
  RETURN r;
END $$;

